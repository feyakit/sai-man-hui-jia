// with the letter of their vehicle registration authority (发牌机关代号). Where a city has several letters
// the main (oldest) one is used, e.g. 郑州 豫A (not 豫V), 青岛 鲁B (not 鲁U), 苏州 苏E (not 苏U).
// Sources: GA 36-2018 and the public lists of 发牌机关代号 (zh.wikipedia 中华人民共和国民用机动车号牌,
// deertools.cn plate table checked 2026-09-28), cross-checked city by city.
// Municipalities and 港澳台 have no city step (their plate stays “京A·春节” etc.).
import type { Province } from './rank/rank';

