/** Cities to offer after a province is picked; empty for municipalities and 港澳台 (no city step). */
export function citiesOf(province: Province | null | undefined): readonly CityPlate[] {
  return province ? CITY_PLATES[province] ?? [] : [];
}

export function findCity(province: Province | null | undefined, name: string | null | undefined): CityPlate | null {
  if (!name) return null;
  return citiesOf(province).find(city => city.name === name) ?? null;
}

/** Letter after the province abbreviation: the city's own code, else the capital's “A”. */
export function plateLetter(province: Province | null | undefined, city: string | null | undefined): string {
  return findCity(province, city)?.code ?? 'A';
}
